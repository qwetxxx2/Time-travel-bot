def build_quiz(epoch: str, count: int = 5) -> list[dict]:
    """Собирает квиз: перемешивает вопросы и варианты ответов."""
    pool = QUESTIONS[epoch][:]
    random.shuffle(pool)
    result = []
    for q in pool[:count]:
        options = q["options"][:]
        correct_text = options[q["correct"]]
        random.shuffle(options)
        result.append({"q": q["q"], "options": options,
                       "correct": options.index(correct_text), "explain": q["explain"]})
    return result